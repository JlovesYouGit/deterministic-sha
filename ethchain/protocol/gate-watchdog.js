  /**
   * Validate exit conditions
   */
  validateExitConditions(exitRoute, exitConditions) {
    // Validate that unique ID matches
    if (exitConditions.uniqueId && exitConditions.uniqueId !== exitRoute.uniqueId.uniqueId) {
      return {
        isValid: false,
        error: 'Unique ID mismatch'
      };
    }

    // Validate computed value allows exit (use immutable result-set value for JJ-tokens)
    const expectedValue = exitRoute.geometricResultSet?.value ?? exitRoute.computedValue?.value;
    if (exitConditions.computedValue != null) {
      const tolerance = 0.01;
      const diff = Math.abs(exitConditions.computedValue - expectedValue);
      if (diff > tolerance) {
        return {
          isValid: false,
          error: 'Computed value mismatch'
        };
      }
    }

    // Validate JJ location
    if (exitConditions.jjLocation && exitConditions.jjLocation !== exitRoute.jjLocation.jjRoot) {
      return {
        isValid: false,
        error: 'JJ location mismatch'
      };
    }

    return {
      isValid: true
    };
  }

